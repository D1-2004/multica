#!/usr/bin/env python3
"""Prepare a frozen local evaluation report or submit it without rebuilding it."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import urllib.error
import urllib.parse
import urllib.request
import uuid

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'server/internal/evalcatalog'
FILES = ('spec.json', 'p0-golden.json', 'office-scenarios.json')


def read_json(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def prepare(args):
    report = read_json(args.input)
    if not isinstance(report, dict) or 'selected_cases' in report or 'catalog' in report:
        raise ValueError('prepare expects runner results with selected_case_ids, without frozen definitions')
    selected = report.pop('selected_case_ids', None)
    if not isinstance(selected, list) or not selected or not all(isinstance(x, str) for x in selected) or len(set(selected)) != len(selected):
        raise ValueError('selected_case_ids must be a nonempty unique string list')
    if not isinstance(report.get('results'), list) or not all(isinstance(x, dict) for x in report['results']):
        raise ValueError('results must be a list')
    result_ids = [x.get('case_id') for x in report['results']]
    if len(result_ids) != len(set(result_ids)) or set(result_ids) != set(selected):
        raise ValueError('every planned case needs exactly one final result; use incomplete for unfinished work')
    run_id = report.get('run_id')
    if not isinstance(run_id, str) or str(uuid.UUID(run_id)) != run_id or uuid.UUID(run_id).int == 0:
        raise ValueError('run_id must be a fixed UUID generated by the runner')
    case_index = {}
    for case in read_json(CATALOG / 'p0-golden.json')['cases']:
        case_index[case['id']] = (case, 'p0', '')
    for scenario in read_json(CATALOG / 'office-scenarios.json')['scenarios']:
        for case in scenario['cases']:
            case_index[case['id']] = (case, 'office', scenario['id'])
    frozen = []
    for case_id in sorted(selected):
        if case_id not in case_index:
            raise ValueError('a planned case ID is not present in the local catalog')
        case, kind, scenario_id = case_index[case_id]
        snapshot = {key: case[key] for key in ('id', 'title', 'roles', 'verifies', 'method')}
        snapshot.update(kind=kind, scenario_id=scenario_id)
        frozen.append(snapshot)
    revision = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, universal_newlines=True).strip()
    paths = ['server/internal/evalcatalog/' + name for name in FILES]
    dirty = bool(subprocess.check_output(['git', 'status', '--porcelain', '--'] + paths, cwd=ROOT))
    digest = hashlib.sha256()
    for name in sorted(FILES):
        digest.update(name.encode('utf-8') + b'\n' + (CATALOG / name).read_bytes() + b'\n')
    if report.get('schema_version', 1) != 1:
        raise ValueError('schema_version must be 1')
    report.update(schema_version=1, selected_cases=frozen, catalog={'revision': revision, 'dirty': dirty, 'sha256': digest.hexdigest()})
    target = Path(args.output)
    # A frozen retry payload must not be overwritten by later definition changes.
    with target.open('x', encoding='utf-8') as output:
        json.dump(report, output, ensure_ascii=False, indent=2)
        output.write('\n')
    print('Frozen report prepared; submit this same file for retries. No network request sent.')


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        raise urllib.error.HTTPError(req.full_url, code, 'redirect refused', headers, fp)


def submit(args):
    origin = urllib.parse.urlsplit(args.endpoint)
    loopback = origin.hostname in ('localhost', '127.0.0.1', '::1')
    if not origin.hostname or origin.username or origin.password or origin.query or origin.fragment or origin.path not in ('', '/') or origin.scheme not in ('https', 'http') or (origin.scheme == 'http' and not loopback):
        raise ValueError('endpoint must be an HTTPS origin; HTTP is allowed only on loopback')
    workspace = str(uuid.UUID(args.workspace_id))
    if uuid.UUID(workspace).int == 0:
        raise ValueError('workspace_id must be a nonzero UUID')
    if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', args.token_env):
        raise ValueError('token-env must name an environment variable')
    token = os.environ.get(args.token_env)
    if not token:
        raise ValueError('the selected token environment variable is empty')
    data = Path(args.input).read_bytes()
    if len(data) > 2 * 1024 * 1024:
        raise ValueError('report exceeds 2 MiB')
    payload = json.loads(data)
    if not isinstance(payload, dict) or payload.get('schema_version') != 1 or not isinstance(payload.get('selected_cases'), list):
        raise ValueError('submit expects the frozen v1 report; prepare the runner results first')
    endpoint = urllib.parse.urlunsplit((origin.scheme, origin.netloc, '', '', '')).rstrip('/')
    request = urllib.request.Request(endpoint + '/api/workspaces/' + workspace + '/eval-reports', data=data, method='POST', headers={'Content-Type': 'application/json', 'Authorization': 'Bearer ' + token})
    opener = urllib.request.build_opener(NoRedirect(), urllib.request.ProxyHandler({}))
    try:
        with opener.open(request, timeout=30) as response:
            status = response.status
            receipt = json.loads(response.read(65537))
    except urllib.error.HTTPError as error:
        print('Upload returned HTTP %s. No automatic retry; reuse the frozen file and run_id.' % error.code, file=sys.stderr)
        return 1
    except (urllib.error.URLError, TimeoutError, OSError, ValueError):
        print('Upload receipt is unconfirmed. Retry with the same frozen file and run_id.', file=sys.stderr)
        return 1
    if status not in (200, 201) or not isinstance(receipt, dict) or receipt.get('workspace_id') != workspace:
        raise ValueError('upload receipt is not valid for the requested workspace')
    report_id = receipt.get('id')
    if not isinstance(report_id, str) or str(uuid.UUID(report_id)) != report_id:
        raise ValueError('upload receipt has no valid report ID')
    if not all(isinstance(receipt.get(key), str) and re.fullmatch(r'[0-9a-f]{64}', receipt[key]) for key in ('content_sha256', 'definition_sha256')):
        raise ValueError('upload receipt has no valid content hashes')
    print('Report received' + (' (replay).' if status == 200 else '.'))
    print(endpoint + '/evals?tab=reports&workspace_id=' + workspace + '&report=' + report_id)
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command')
    build = commands.add_parser('prepare', help='Freeze selected local definitions into a new report file')
    build.add_argument('--input', required=True, help='Runner JSON with selected_case_ids and results')
    build.add_argument('--output', required=True, help='New immutable submission file; must not already exist')
    upload = commands.add_parser('submit', help='Submit the already frozen file with a human PAT')
    upload.add_argument('--input', required=True)
    upload.add_argument('--endpoint', required=True)
    upload.add_argument('--workspace-id', required=True)
    upload.add_argument('--token-env', default='MULTICA_TOKEN')
    args = parser.parse_args()
    try:
        if args.command == 'prepare':
            prepare(args)
            return 0
        if args.command == 'submit':
            return submit(args)
        parser.error('choose prepare or submit')
    except (ValueError, KeyError, TypeError, OSError, subprocess.CalledProcessError):
        # Never echo potentially sensitive runner data or response bodies.
        print('Report command failed: check the v1 contract, file paths, fixed IDs and credentials. No input data printed.', file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
